#!/usr/bin/env node
/**
 * Generates `src/parsers/fhir-xml/cardinality.generated.ts` — which elements
 * repeat, per resource type.
 *
 * FHIR XML carries no schema, so a lone `<jurisdiction>` is indistinguishable
 * from a one-item list and the parser has to decide. It used to decide from a
 * hand-written list of thirty names, which covered thirty of the 483 element
 * names R4 makes `0..*`.
 *
 * Keyed by resource type rather than by name alone, because the same name has
 * different cardinality in different places: `Patient.name` is `0..*` and
 * `Organization.name` is a `0..1` string.
 *
 *   node scripts/generate-xml-cardinality.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const digest = JSON.parse(
  readFileSync(new URL('../spec/r4-elements.json', import.meta.url), 'utf8'),
);

/**
 * `extension`, `contained` and `modifierExtension` repeat on every resource
 * and appear in none of them: the element digest leaves inherited elements out
 * so the shape tables are not asked to declare plumbing. Emitted separately
 * rather than copied into all 145 entries.
 */
const common = JSON.parse(readFileSync(new URL('../spec/r4-common.json', import.meta.url), 'utf8'));
const repeatingCommon = Object.entries(common)
  .filter(([, element]) => element.list)
  .map(([name]) => name)
  .sort();

/** `''` holds the resource's own repeating elements; other keys are backbones. */
const TOP_LEVEL = '';
const TOP_LEVEL_KEY = '';

const table = {};

/**
 * Where a nested resource genuinely lives, as `resourceType.parent` — only
 * `Bundle.entry.resource` and `Parameters.parameter.resource` in all of R4.
 *
 * The parser used to treat any element named `resource`, `contained` or
 * `outcome` as a wrapper, which mangled the eighteen other places those names
 * appear: `Procedure.outcome` is a CodeableConcept and `AuditEvent.outcome` is
 * a code, and both were destroyed by being read as a resource.
 */
const containers = [];

for (const [resourceType, fields] of Object.entries(digest).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const levels = {};
  const top = [];

  for (const [name, element] of Object.entries(fields)) {
    if (element.list) top.push(name);
    if (element.types?.[0] === 'Resource')
      containers.push(`${resourceType}.${TOP_LEVEL_KEY}.${name}`);
    for (const [child, c] of Object.entries(element.fields ?? {})) {
      if (c.types?.[0] === 'Resource') containers.push(`${resourceType}.${name}.${child}`);
    }

    const children = Object.entries(element.fields ?? {})
      .filter(([, child]) => child.list)
      .map(([child]) => child)
      .sort();

    if (children.length > 0) levels[name] = children;
  }

  if (top.length > 0) levels[TOP_LEVEL] = top.sort();
  if (Object.keys(levels).length > 0) table[resourceType] = levels;
}

const source = `// Generated by scripts/generate-xml-cardinality.mjs. Do not edit.
//
// Which elements repeat, per resource type. XML cannot express cardinality, so
// the parser needs this to know that a lone <jurisdiction> is a one-item list
// while a lone <description> is not.
//
// The empty key holds a resource's own repeating elements; every other key is a
// backbone element, holding the repeating elements inside it.

export const REPEATING_BY_RESOURCE: Readonly<
  Record<string, Readonly<Record<string, readonly string[]>>>
> = ${JSON.stringify(table, null, 2)};

/** Inherited from Resource and DomainResource, so repeating on everything. */
export const REPEATING_COMMON: readonly string[] = ${JSON.stringify(repeatingCommon)};

/**
 * Where FHIR XML nests a resource one level deeper than JSON does, as
 * \`resourceType.parent.element\` with an empty parent for the top level.
 *
 * Only the positions R4 actually types as \`Resource\`. Matching the element
 * name alone destroys \`Procedure.outcome\`, which is a CodeableConcept.
 */
export const RESOURCE_CONTAINER_AT: readonly string[] = ${JSON.stringify(containers.sort())};
`;

writeFileSync(new URL('../src/parsers/fhir-xml/cardinality.generated.ts', import.meta.url), source);

const names = new Set();
for (const levels of Object.values(table)) {
  for (const list of Object.values(levels)) for (const name of list) names.add(name);
}
console.log(
  `wrote src/parsers/fhir-xml/cardinality.generated.ts — ${Object.keys(table).length} resources, ${names.size} distinct repeating names, ${(source.length / 1024).toFixed(0)} KB`,
);
