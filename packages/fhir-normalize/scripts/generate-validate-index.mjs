#!/usr/bin/env node
/**
 * Generates `src/validate/r4-index.generated.ts` — what `validateResource`
 * checks a payload against.
 *
 * Derived from `spec/r4-elements.json` rather than written by hand, so the
 * validator cannot claim something the specification does not say. A test
 * regenerates this and fails if the committed file differs.
 *
 *   node scripts/generate-validate-index.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const digest = JSON.parse(
  readFileSync(new URL('../spec/r4-elements.json', import.meta.url), 'utf8'),
);

/**
 * What every resource inherits from Resource and DomainResource. Absent from
 * the element digest because the shape tables are not asked to declare
 * plumbing, but a payload can still get them wrong: `extension` is `0..*`, and
 * a single object there is malformed.
 */
const common = JSON.parse(readFileSync(new URL('../spec/r4-common.json', import.meta.url), 'utf8'));

/**
 * Keeps only what validation reads. `types` is carried for a choice, because
 * the permitted set is what tells `valueQuantity` from `valueReference`, and
 * dropped elsewhere where knowing the datatype would not change any answer.
 */
const slim = (element) => {
  const out = {};
  if (element.list) out.list = true;
  if (element.required) out.required = true;
  if (element.choice) {
    out.choice = true;
    out.types = element.types;
  }

  const children = Object.entries(element.fields ?? {});
  if (children.length > 0) {
    out.fields = Object.fromEntries(children.map(([name, child]) => [name, slim(child)]));
  }

  return out;
};

const index = Object.fromEntries(
  Object.entries(digest)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([resourceType, fields]) => [
      resourceType,
      Object.fromEntries(Object.entries(fields).map(([name, e]) => [name, slim(e)])),
    ]),
);

/**
 * Every datatype name the specification uses, collected from the digest.
 *
 * Needed to tell a disallowed choice type from an element R4 simply does not
 * have: `valueReference` on an Observation is a Reference where R4 permits
 * none, while `valueSet` is not a choice at all. Derived rather than listed,
 * so it cannot fall behind the digest.
 */
const fhirTypes = new Set();
const collect = (fields) => {
  for (const element of Object.values(fields)) {
    for (const type of element.types ?? []) fhirTypes.add(type);
    if (element.fields) collect(element.fields);
  }
};
for (const fields of Object.values(digest)) collect(fields);

/**
 * The positions R4 types as holding a whole nested resource.
 *
 * Derived rather than written down, the same way the XML parser derives its
 * copy: in R4 the answer is `Bundle.entry.resource` and
 * `Parameters.parameter.resource`, and hardcoding two strings would be a claim
 * about the specification that nothing rechecks. Paths are relative to the
 * resource, so a top-level container would appear here as a bare element name.
 */
const containers = {};

for (const [resourceType, fields] of Object.entries(digest)) {
  const paths = [];

  for (const [name, element] of Object.entries(fields)) {
    if (element.types?.[0] === 'Resource') paths.push(name);
    for (const [child, c] of Object.entries(element.fields ?? {})) {
      if (c.types?.[0] === 'Resource') paths.push(`${name}.${child}`);
    }
  }

  if (paths.length > 0) containers[resourceType] = paths.sort();
}

const source = `// Generated by scripts/generate-validate-index.mjs. Do not edit.
//
// Every R4 element, with the cardinality, required flag, and permitted choice
// types that \`validateResource\` checks against. One level inside each backbone
// element is included, which is as deep as the spec digest goes.

import type { IndexedElement } from './types';

export const R4_INDEX: Readonly<Record<string, Readonly<Record<string, IndexedElement>>>> =
  ${JSON.stringify(index, null, 2).replace(/\n/g, '\n  ')};

export const COMMON_ELEMENTS: Readonly<Record<string, IndexedElement>> =
  ${JSON.stringify(
    Object.fromEntries(
      Object.entries(common).map(([name, e]) => [name, e.list ? { list: true } : {}]),
    ),
    null,
    2,
  ).replace(/\n/g, '\n  ')};

/**
 * Where a resource nests another whole resource, relative to the resource.
 *
 * \`contained\` is not here: every resource may carry it, so it is handled
 * directly rather than repeated 146 times.
 */
export const RESOURCE_CONTAINERS: Readonly<Record<string, readonly string[]>> =
  ${JSON.stringify(containers, null, 2).replace(/\n/g, '\n  ')};

/** Lowercased, because the spec writes \`string\` and a payload writes \`valueString\`. */
export const FHIR_TYPE_NAMES: ReadonlySet<string> = new Set(
  ${JSON.stringify([...fhirTypes].map((t) => t.toLowerCase()).sort())},
);
`;

writeFileSync(new URL('../src/validate/r4-index.generated.ts', import.meta.url), source);

console.log(
  `resource containers: ${Object.entries(containers)
    .flatMap(([r, paths]) => paths.map((path) => `${r}.${path}`))
    .join(', ')}`,
);

const top = Object.values(index).reduce((n, f) => n + Object.keys(f).length, 0);
const nested = Object.values(index).reduce(
  (n, f) => n + Object.values(f).reduce((m, e) => m + Object.keys(e.fields ?? {}).length, 0),
  0,
);
console.log(
  `wrote src/validate/r4-index.generated.ts — ${Object.keys(index).length} resources, ${top} elements, ${nested} backbone children, ${(source.length / 1024).toFixed(0)} KB`,
);
