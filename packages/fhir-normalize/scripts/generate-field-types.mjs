#!/usr/bin/env node
/**
 * Generates `src/simplified/fields.generated.ts` — one interface per resource
 * type, giving `simplifyResource` a real return type instead of a string index
 * signature.
 *
 * Derived from the shape tables rather than written by hand, so the types
 * cannot drift from the runtime behaviour they describe. A test regenerates
 * this and fails if the committed file differs.
 *
 *   node scripts/generate-field-types.mjs
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { RESOURCE_SHAPE, TYPE_SUFFIX_KIND } = require('../dist/simplified.cjs');

/** FIELD_KIND -> the normalized value type it produces. */
const VALUE_TYPE = {
  concept: 'NormalizedConcept',
  quantity: 'NormalizedQuantity',
  reference: 'NormalizedReference',
  period: 'NormalizedPeriod',
  range: 'NormalizedRange',
  ratio: 'NormalizedRatio',
  name: 'NormalizedName',
  contact: 'NormalizedContactPoint',
  address: 'NormalizedAddress',
  identifier: 'NormalizedIdentifier',
  // `toAnnotation` returns a string value, whatever the input shape.
  annotation: 'NormalizedString',
  primitive: 'PrimitiveValue',
  choice: 'NormalizedValue',
};

/** VALUE_KIND -> the interface that kind of value is typed as. */
const KIND_TYPE = {
  concept: 'NormalizedConcept',
  quantity: 'NormalizedQuantity',
  reference: 'NormalizedReference',
  period: 'NormalizedPeriod',
  range: 'NormalizedRange',
  ratio: 'NormalizedRatio',
  name: 'NormalizedName',
  contact: 'NormalizedContactPoint',
  address: 'NormalizedAddress',
  identifier: 'NormalizedIdentifier',
  string: 'NormalizedString',
  boolean: 'NormalizedBoolean',
  number: 'NormalizedNumber',
  dateTime: 'NormalizedDateTime',
  // No entry for `unknown`: TYPE_SUFFIX_KIND never maps a suffix to it, so a
  // choice can never normalize to one.
};

const capitalize = (value) => value[0].toUpperCase() + value.slice(1);

/**
 * The value types a choice can actually produce.
 *
 * Read through `TYPE_SUFFIX_KIND`, the same table the resolver uses, so the
 * narrowing cannot claim something the runtime would never return. A declared
 * FHIR type with no entry there — `SampledData`, say — is unreachable: the
 * resolver skips suffixes it does not recognise, so it is left out rather
 * than widening the union.
 */
const choiceTypes = (types) => {
  const mapped = types
    .map((type) => TYPE_SUFFIX_KIND[capitalize(type)])
    .filter((kind) => kind !== undefined)
    .map((kind) => KIND_TYPE[kind]);

  return [...new Set(mapped)].sort();
};

const indentOf = (depth) => '  '.repeat(depth);

/** The type expression for one field spec. */
const typeFor = (spec, depth) => {
  if (spec.kind === 'group') {
    const fields = spec.fields ?? {};
    const inner = Object.entries(fields)
      .map(([name, child]) => `${indentOf(depth + 1)}${name}?: ${typeFor(child, depth + 1)};`)
      .join('\n');
    const shape = inner === '' ? '{}' : `{\n${inner}\n${indentOf(depth)}}`;
    return spec.list === false ? shape : `Array<${shape}>`;
  }

  let base = VALUE_TYPE[spec.kind] ?? 'NormalizedValue';

  // A choice that declares its permitted types narrows to just those.
  if (spec.kind === 'choice' && Array.isArray(spec.types)) {
    const narrowed = choiceTypes(spec.types);
    if (narrowed.length > 0) base = narrowed.join(' | ');
  }

  const needsParens = base.includes(' | ');
  return spec.list === true ? `Array<${base}>` : needsParens ? `(${base})` : base;
};

const names = Object.keys(RESOURCE_SHAPE).sort();

const interfaces = names.map((resourceType) => {
  const { fields } = RESOURCE_SHAPE[resourceType];
  const members = Object.entries(fields)
    .map(([name, spec]) => `  ${name}?: ${typeFor(spec, 1)};`)
    .join('\n');

  return `/** Normalized fields of a \`${resourceType}\`. */\nexport interface ${resourceType}Fields {\n${members}\n}`;
});

const mapEntries = names.map((n) => `  ${n}: ${n}Fields;`).join('\n');

const source = `// Generated by scripts/generate-field-types.mjs. Do not edit.
//
// One interface per resource type, derived from the shape tables so the types
// cannot drift from what \`simplifyResource\` actually returns.

import type {
  NormalizedAddress,
  NormalizedBoolean,
  NormalizedConcept,
  NormalizedContactPoint,
  NormalizedDateTime,
  NormalizedIdentifier,
  NormalizedName,
  NormalizedNumber,
  NormalizedPeriod,
  NormalizedQuantity,
  NormalizedRange,
  NormalizedRatio,
  NormalizedReference,
  NormalizedString,
  NormalizedValue,
} from './types';

/** What a \`primitive\` field normalizes to — the type is read from the value. */
export type PrimitiveValue =
  | NormalizedString
  | NormalizedBoolean
  | NormalizedNumber
  | NormalizedDateTime;

${interfaces.join('\n\n')}

/** Every resource type with a declared shape, keyed by \`resourceType\`. */
export interface ResourceFieldMap {
${mapEntries}
}
`;

writeFileSync(new URL('../src/simplified/fields.generated.ts', import.meta.url), source);

const members = names.reduce((n, r) => n + Object.keys(RESOURCE_SHAPE[r].fields).length, 0);
console.log(
  `wrote src/simplified/fields.generated.ts — ${names.length} interfaces, ${members} members, ${(source.length / 1024).toFixed(0)} KB`,
);
